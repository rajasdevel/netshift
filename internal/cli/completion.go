package cli

import (
	"fmt"
	"io"
	"slices"
	"strings"

	"github.com/rajasdevel/netshift/internal/cmdline"
)

// completionShells are the shells completion writes a script for.
var completionShells = []string{"bash", "fish", "zsh"}

// completionCommandLine describes completion.
func completionCommandLine() *cmdline.Line {
	return cmdline.New("completion", "completion bash | zsh | fish",
		"Print a shell completion script. The README shows how to load it in each shell.")
}

// handleCompletion prints the completion script for one shell.
func handleCompletion(args []string) error {
	f := completionCommandLine()
	positional, err := f.ParseArgs(args)
	if err != nil {
		return err
	}
	if len(positional) != 1 || !slices.Contains(completionShells, positional[0]) {
		return f.Errorf("expected one shell: %s", strings.Join(completionShells, ", "))
	}
	_, err = io.WriteString(runtimeOutput, completionScript(positional[0]))
	return err
}

// completionSpec is what a completion script knows about one command line:
// its options, and the words its first argument may be.
type completionSpec struct {
	name    string // the command, or "" for the options before COMMAND
	about   string // a short description
	options []cmdline.Option
	choices []string
}

// completionSpecs returns the global options, whose first argument is the
// command, and then each command in name order. Both come from the command
// table and the commands' cmdline.Line, so the scripts cannot drift from
// what the commands accept.
func completionSpecs() (completionSpec, []completionSpec) {
	g, _ := globalCommandLine()
	global := completionSpec{options: g.Options()}
	var specs []completionSpec
	for _, c := range commands() {
		line := c.line()
		specs = append(specs, completionSpec{name: c.name, about: firstSentence(line.Summary()), options: line.Options(), choices: c.choices})
	}
	slices.SortFunc(specs, func(a, b completionSpec) int { return strings.Compare(a.name, b.name) })
	for _, s := range specs {
		global.choices = append(global.choices, s.name)
	}
	return global, specs
}

// firstSentence is a summary's first sentence without its period, short
// enough for a completion menu.
func firstSentence(s string) string {
	if i := strings.Index(s, ". "); i >= 0 {
		s = s[:i]
	}
	return strings.TrimSuffix(s, ".")
}

// optionNames returns the names of the spec's options, or of those that take
// a value, or of those whose value is a file name.
func (s completionSpec) optionNames(valued, files bool) []string {
	var names []string
	for _, o := range s.options {
		if valued && o.Value == "" || files && !fileValue(o.Value) {
			continue
		}
		names = append(names, o.Name)
	}
	return names
}

// fileValue reports whether an option's value placeholder is a file name.
func fileValue(placeholder string) bool { return placeholder == "FILE" || placeholder == "executable" }

// completionScript returns the completion script for shell.
func completionScript(shell string) string {
	global, specs := completionSpecs()
	switch shell {
	case "bash":
		return bashCompletion(global, specs)
	case "zsh":
		return zshCompletion(global, specs)
	default:
		return fishCompletion(global, specs)
	}
}

// singleQuote quotes s for bash and zsh, always.
func singleQuote(s string) string { return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'" }

// fishQuote quotes s for fish, whose single quotes escape \ and '.
func fishQuote(s string) string {
	return "'" + strings.NewReplacer(`\`, `\\`, `'`, `\'`).Replace(s) + "'"
}

// bashLists assigns a spec's lists to the bash script's variables.
func bashLists(s completionSpec) string {
	var dashed []string
	for _, name := range s.optionNames(false, false) {
		dashed = append(dashed, "--"+name)
	}
	return fmt.Sprintf("opts=%s valued=%s filed=%s args=%s", singleQuote(strings.Join(dashed, " ")),
		singleQuote(strings.Join(s.optionNames(true, false), " ")), singleQuote(strings.Join(s.optionNames(true, true), " ")),
		singleQuote(strings.Join(s.choices, " ")))
}

// bashCompletion returns the bash script. It walks the words before the
// cursor as netshift parses them: global options and their values, the
// command, then the command's options and arguments, until "--" ends options.
// It completes option names, the first argument's choices, and file names
// for options that take a file. bash 3.2 lacks compopt, so there an
// option's value that is not a file falls back to file names.
func bashCompletion(global completionSpec, specs []completionSpec) string {
	var b strings.Builder
	b.WriteString(`# bash completion for netshift, generated by "netshift completion bash".
# Load it from ~/.bashrc with: eval "$(netshift completion bash)"

# _netshift_has reports whether the space-separated list $1 contains $2.
_netshift_has() {
	case " $1 " in *" $2 "*) return 0 ;; esac
	return 1
}

_netshift() {
	local cur=${COMP_WORDS[COMP_CWORD]} word name command= expect= ended= i=1 count=0
`)
	fmt.Fprintf(&b, "\tlocal %s\n", bashLists(global))
	b.WriteString(`	while [ "$i" -lt "$COMP_CWORD" ]; do
		word=${COMP_WORDS[i]}
		if [ -z "$ended" ] && [ "$word" = -- ]; then
			[ -n "$command" ] && ended=1
		elif [ -z "$ended" ] && [ "${word#-}" != "$word" ] && [ "$word" != - ]; then
			name=${word#-}
			name=${name#-}
			if [ "${COMP_WORDS[i+1]}" = = ]; then
				# bash splits --name=value at "=".
				if [ $((i + 1)) -eq "$COMP_CWORD" ] || [ $((i + 2)) -eq "$COMP_CWORD" ]; then
					expect=$name
				fi
				i=$((i + 2))
			elif _netshift_has "$valued" "$name"; then
				[ $((i + 1)) -eq "$COMP_CWORD" ] && expect=$name
				i=$((i + 1))
			fi
		elif [ -z "$command" ]; then
			command=$word
			case $command in
`)
	for _, s := range specs {
		fmt.Fprintf(&b, "\t\t\t%s) %s ;;\n", s.name, bashLists(s))
	}
	b.WriteString(`			*) opts= valued= filed= args= ;;
			esac
		else
			count=$((count + 1))
		fi
		i=$((i + 1))
	done
	if [ -n "$expect" ]; then
		# An option's value: leave file names to -o default, and offer
		# nothing for other values.
		_netshift_has "$filed" "$expect" || compopt +o default 2>/dev/null
		return 0
	fi
	compopt +o default 2>/dev/null
	if [ -z "$ended" ] && [ "${cur#-}" != "$cur" ]; then
		COMPREPLY=($(compgen -W "$opts" -- "$cur"))
	elif [ "$count" -eq 0 ]; then
		COMPREPLY=($(compgen -W "$args" -- "$cur"))
	fi
}

complete -o default -F _netshift netshift
`)
	return b.String()
}

// zshLists assigns a spec's lists to the zsh script's arrays. Options carry
// their descriptions for _describe; choices carry those in about, which only
// the global spec, whose choices are the commands, passes.
func zshLists(s completionSpec, about map[string]string) string {
	var opts, args []string
	for _, o := range s.options {
		opts = append(opts, singleQuote("--"+o.Name+":"+o.Usage))
	}
	for _, c := range s.choices {
		if about[c] != "" {
			c += ":" + about[c]
		}
		args = append(args, singleQuote(c))
	}
	return fmt.Sprintf("opts=(%s) valued=(%s) filed=(%s) args=(%s)", strings.Join(opts, " "),
		strings.Join(s.optionNames(true, false), " "), strings.Join(s.optionNames(true, true), " "), strings.Join(args, " "))
}

// zshCompletion returns the zsh script: the bash script's walk, with
// descriptions, _files for file values, and --name=value. Loaded from a
// file on $fpath it is the _netshift function; sourced, it registers itself.
func zshCompletion(global completionSpec, specs []completionSpec) string {
	about := map[string]string{}
	for _, s := range specs {
		about[s.name] = s.about
	}
	var b strings.Builder
	b.WriteString(`#compdef netshift
# zsh completion for netshift, generated by "netshift completion zsh".
# Load it from ~/.zshrc, after compinit, with: source <(netshift completion zsh)
# or save it as _netshift in a directory on $fpath.

_netshift() {
	local word name command expect ended
	local -i i=2 count=0
	local -a opts valued filed args
`)
	fmt.Fprintf(&b, "\t%s\n", zshLists(global, about))
	b.WriteString(`	while (( i < CURRENT )); do
		word=$words[i]
		if [[ -z $ended && $word == -- ]]; then
			[[ -n $command ]] && ended=1
		elif [[ -z $ended && $word == -?* ]]; then
			name=${word#-}
			name=${name#-}
			if (( $valued[(Ie)$name] )); then
				(( i + 1 == CURRENT )) && expect=$name
				(( i++ ))
			fi
		elif [[ -z $command ]]; then
			command=$word
			case $command in
`)
	for _, s := range specs {
		fmt.Fprintf(&b, "\t\t\t(%s) %s ;;\n", s.name, zshLists(s, nil))
	}
	b.WriteString(`			(*) opts=() valued=() filed=() args=() ;;
			esac
		else
			(( count++ ))
		fi
		(( i++ ))
	done
	if [[ -z $expect && -z $ended && $PREFIX == -?*=* ]]; then
		name=${PREFIX%%=*}
		name=${name#-}
		name=${name#-}
		if (( $valued[(Ie)$name] )); then
			expect=$name
			compset -P '*='
		fi
	fi
	if [[ -n $expect ]]; then
		(( $filed[(Ie)$expect] )) && _files
		return
	fi
	if [[ -z $ended && $PREFIX == -* ]]; then
		_describe -t options option opts
	elif (( count == 0 )); then
		if [[ -z $command ]]; then
			_describe -t commands command args
		else
			_describe -t arguments argument args
		fi
	fi
}

if [[ $funcstack[1] == _netshift ]]; then
	_netshift "$@"
else
	compdef _netshift netshift
fi
`)
	return b.String()
}

// fishCompletion returns the fish script. __netshift_at walks the tokens as
// the bash script does, so each completion can name the command it belongs
// to; fish itself completes values, file names, and --name=value.
func fishCompletion(global completionSpec, specs []completionSpec) string {
	var b strings.Builder
	b.WriteString(`# fish completion for netshift, generated by "netshift completion fish".
# Load it with: netshift completion fish | source
# or save it as ~/.config/fish/completions/netshift.fish.

# __netshift_at succeeds when the command being completed is $argv[1] ("" for
# none yet) and, when $argv[2] is given, that many arguments follow it.
function __netshift_at
    set -l tokens (commandline -opc)
`)
	fmt.Fprintf(&b, "    set -l valued%s\n", fishWords(global.optionNames(true, false)))
	b.WriteString(`    set -l command ''
    set -l ended ''
    set -l count 0
    set -l i 2
    while test $i -le (count $tokens)
        set -l word $tokens[$i]
        if test -z "$ended"; and test "$word" = --
            test -n "$command"; and set ended 1
        else if test -z "$ended"; and string match -q -- '-?*' $word
            set -l name (string replace -r -- '^--?' '' $word)
            contains -- $name $valued; and set i (math $i + 1)
        else if test -z "$command"
            set command $word
            switch $command
`)
	for _, s := range specs {
		fmt.Fprintf(&b, "                case %s\n                    set valued%s\n", s.name, fishWords(s.optionNames(true, false)))
	}
	b.WriteString(`                case '*'
                    set valued
            end
        else
            set count (math $count + 1)
        end
        set i (math $i + 1)
    end
    test "$command" = "$argv[1]"; or return 1
    test (count $argv) -lt 2; or test $count -eq $argv[2]
end

complete -c netshift -f
`)
	fishOptions(&b, `__netshift_at ""`, global.options)
	for _, s := range specs {
		fmt.Fprintf(&b, "complete -c netshift -n %s -a %s -d %s\n", fishQuote(`__netshift_at "" 0`), s.name, fishQuote(s.about))
	}
	for _, s := range specs {
		fishOptions(&b, "__netshift_at "+s.name, s.options)
		if len(s.choices) != 0 {
			fmt.Fprintf(&b, "complete -c netshift -n %s -a %s\n", fishQuote("__netshift_at "+s.name+" 0"), fishQuote(strings.Join(s.choices, " ")))
		}
	}
	return b.String()
}

// fishWords lists option names as arguments, each after a space.
func fishWords(names []string) string {
	var b strings.Builder
	for _, name := range names {
		b.WriteString(" " + name)
	}
	return b.String()
}

// fishOptions writes one completion for each option under condition: -F
// completes a file value, -x any other value.
func fishOptions(b *strings.Builder, condition string, options []cmdline.Option) {
	for _, o := range options {
		value := ""
		switch {
		case fileValue(o.Value):
			value = " -r -F"
		case o.Value != "":
			value = " -x"
		}
		fmt.Fprintf(b, "complete -c netshift -n %s -l %s%s -d %s\n", fishQuote(condition), o.Name, value, fishQuote(o.Usage))
	}
}
